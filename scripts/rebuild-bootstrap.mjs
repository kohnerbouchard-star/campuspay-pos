import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sqlDir = path.join(root, 'supabase', 'schema');
const files = fs.readdirSync(sqlDir).filter((name) => name.endsWith('.sql')).sort();
const banner = '-- CampusPay modular Supabase bootstrap\n-- Generated from supabase/schema/*.sql. Do not edit this file directly.\n\n';
const body = files.map((name) => `-- BEGIN ${name}\n${fs.readFileSync(path.join(sqlDir, name), 'utf8').trim()}\n-- END ${name}\n`).join('\n');
fs.writeFileSync(path.join(root, 'supabase', 'bootstrap.sql'), banner + body + '\n');
console.log(`Built supabase/bootstrap.sql from ${files.length} modules.`);
